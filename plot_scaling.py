import matplotlib.pyplot as plt

# Data from SLURM output
threads = [1, 4, 8, 12, 16]

# Amdahl's Law Data (Strong Scaling)
amdahl_time = [4.980, 1.689, 1.136, 1.049, 0.926]
amdahl_speedup = [amdahl_time[0] / t for t in amdahl_time]
ideal_speedup = threads

# Gustafson's Law Data (Weak Scaling)
gustafson_time = [0.125, 0.223, 0.325, 0.400, 0.534]

# Create figure and subplots
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))

# Plot 1: Amdahl's Law (Speedup)
ax1.plot(threads, amdahl_speedup, marker='o', linestyle='-', color='b', linewidth=2, label='Actual Speedup')
ax1.plot(threads, ideal_speedup, marker='', linestyle='--', color='gray', label='Ideal Linear Speedup')
ax1.set_title("Amdahl's Law: Strong Scaling (2000x2000 Fixed Grid)", fontsize=12, fontweight='bold')
ax1.set_xlabel('Number of Threads', fontsize=11)
ax1.set_ylabel('Speedup (T1 / Tp)', fontsize=11)
ax1.set_xticks(threads)
ax1.grid(True, linestyle=':', alpha=0.7)
ax1.legend()

# Plot 2: Gustafson's Law (Execution Time)
ax2.plot(threads, gustafson_time, marker='s', linestyle='-', color='r', linewidth=2, label='Execution Time')
ax2.set_title("Gustafson's Law: Weak Scaling (Constant Workload/Thread)", fontsize=12, fontweight='bold')
ax2.set_xlabel('Number of Threads', fontsize=11)
ax2.set_ylabel('Execution Time (seconds)', fontsize=11)
ax2.set_xticks(threads)
ax2.grid(True, linestyle=':', alpha=0.7)
ax2.legend()

# Format and save
plt.tight_layout()
plt.savefig('scaling_graphs.png', dpi=300, bbox_inches='tight')
print("Graph saved successfully as scaling_graphs.png")